/** 점자 문자 → 켜진 점 번호 배열. dots('⠣') => [1, 2, 6] */
export const dots = (ch) => {
  const v = ch.codePointAt(0) - 0x2800;
  return [1, 2, 3, 4, 5, 6].filter((n) => v & (1 << (n - 1)));
};

export const lookup = (table, jamo) => table.find(([j]) => j === jamo)?.[1];
